/// Serialization helpers for generated OpenAPI artifacts.
library;

import 'dart:convert';

import 'package:axle_core/axle_core.dart';

/// The name of the generated Dart constant.
const generatedSpecConstantName = 'axleOpenApiJson';

/// Serializes a generated document to the on-disk JSON artifact.
String generateJsonArtifact(OpenApiDocument document) {
  return '${document.toJsonString()}\n';
}

/// Serializes a generated document to the on-disk YAML artifact.
String generateYamlArtifact(OpenApiDocument document) {
  return '${_encodeYamlNode(document.toJson(), 0).join('\n')}\n';
}

List<String> _encodeYamlNode(Object? value, int indent) {
  final prefix = ' ' * indent;
  if (value is Map) {
    if (value.isEmpty) return ['$prefix{}'];
    final lines = <String>[];
    for (final entry in value.entries) {
      final key = _yamlKey(entry.key.toString());
      final child = entry.value;
      if ((child is Map && child.isNotEmpty) ||
          (child is List && child.isNotEmpty)) {
        lines.add('$prefix$key:');
        lines.addAll(_encodeYamlNode(child, indent + 2));
      } else {
        lines.add('$prefix$key: ${_yamlScalar(child)}');
      }
    }
    return lines;
  }
  if (value is List) {
    if (value.isEmpty) return ['$prefix[]'];
    final lines = <String>[];
    for (final child in value) {
      if (child is Map && child.isNotEmpty) {
        final encoded = _encodeYamlNode(child, indent + 2);
        lines.add('$prefix- ${encoded.first.substring(indent + 2)}');
        lines.addAll(encoded.skip(1));
      } else if (child is List) {
        lines.add('$prefix- ${jsonEncode(child)}');
      } else {
        lines.add('$prefix- ${_yamlScalar(child)}');
      }
    }
    return lines;
  }
  return ['$prefix${_yamlScalar(value)}'];
}

String _yamlKey(String value) {
  return _canUsePlainYaml(value) ? value : jsonEncode(value);
}

String _yamlScalar(Object? value) {
  if (value is String) {
    return _canUsePlainYaml(value) ? value : jsonEncode(value);
  }
  if (value is num || value is bool) return value.toString();
  if (value == null) return 'null';
  return jsonEncode(value);
}

bool _canUsePlainYaml(String value) {
  if (value.isEmpty) return false;
  if (!RegExp(r'^[A-Za-z_][A-Za-z0-9_.-]*$').hasMatch(value)) return false;
  return !const {
    'true',
    'false',
    'null',
    'yes',
    'no',
    'on',
    'off',
    'y',
    'n',
  }.contains(value.toLowerCase());
}

/// Generates a Dart source file containing the OpenAPI document as a constant.
///
/// The JSON is escaped into a single-quoted Dart string, so the generated value
/// is available in AOT builds without reading a file at runtime.
String generateDartArtifact(String json) {
  final literal = _dartStringLiteral(json);
  return '''
// GENERATED CODE - DO NOT MODIFY BY HAND.
// Generated by axle_cli. Run `dart run axle_cli:axle gen` to regenerate.

/// The generated OpenAPI document as a JSON string.
const String $generatedSpecConstantName =
    $literal;
''';
}

String _dartStringLiteral(String value) {
  final buffer = StringBuffer("'");
  for (final rune in value.runes) {
    switch (rune) {
      case 0x5C: // backslash
        buffer.write(r'\\');
      case 0x27: // single quote
        buffer.write(r"\'");
      case 0x24: // dollar
        buffer.write(r'\$');
      case 0x0A: // newline
        buffer.write(r'\n');
      case 0x0D: // carriage return
        buffer.write(r'\r');
      case 0x09: // tab
        buffer.write(r'\t');
      default:
        if (rune < 0x20) {
          buffer.write('\\u{${rune.toRadixString(16)}}');
        } else {
          buffer.writeCharCode(rune);
        }
    }
  }
  buffer.write("'");
  return buffer.toString();
}
