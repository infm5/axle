/// Relic integration for axle.
library;

import 'dart:io';
import 'dart:typed_data';

import 'package:axle_core/axle_core.dart';
import 'package:mime/mime.dart';
import 'package:path/path.dart' as p;
import 'package:relic/relic.dart';

/// Returns a Relic [Handler] that serves a generated OpenAPI document.
///
/// The [spec] is the JSON string produced by `axle gen`. When [noCache] is
/// `true`, the response tells intermediaries and browsers not to cache it.
Handler openApiJsonHandler(String spec, {bool noCache = true}) {
  final docs = AxleDocs(spec: spec, noCache: noCache);
  return (Request request) => _jsonResponse(docs);
}

/// Returns a Relic [Handler] that serves a Swagger UI page.
///
/// The page fetches its OpenAPI document from [specPath]. Use [title] to set
/// the browser title and [swaggerUiUrl] to serve the Swagger UI assets from a
/// different location.
Handler swaggerUiHandler({
  String specPath = '/openapi.json',
  String title = 'API Docs',
  String swaggerUiUrl = defaultSwaggerUiUrl,
  bool noCache = true,
}) {
  final html = swaggerUiHtml(
    specUrl: specPath,
    title: title,
    swaggerUiUrl: swaggerUiUrl,
  );
  return (Request request) => Response.ok(
    body: Body.fromString(html, mimeType: MimeType.html),
    headers: noCache ? _cacheHeaders() : null,
  );
}

/// Adds OpenAPI and Swagger UI routes to a [RelicApp].
extension AxleRelicDocs on RelicApp {
  /// Mounts the generated OpenAPI document and Swagger UI.
  ///
  /// [spec] is the JSON string produced by `axle gen`. The document is served
  /// at [specPath] and the UI at [docsPath]. Both paths must start with `/`.
  ///
  /// When [title] is omitted, the UI title is read from the document's
  /// `info.title`.
  ///
  /// Pass [swaggerUiDirectory] to serve the assets generated by `axle gen` from
  /// that directory. The UI then loads assets from [swaggerUiPath]. When
  /// [swaggerUiDirectory] is omitted, the UI uses [swaggerUiUrl], which
  /// defaults to the pinned CDN distribution.
  ///
  /// ```dart
  /// import 'package:axle_relic/axle_relic.dart';
  /// import 'package:your_package/src/generated/openapi.g.dart';
  ///
  /// final app = RelicApp();
  /// app.mountAxleDocs(
  ///   spec: axleOpenApiJson,
  ///   swaggerUiDirectory: 'assets/swagger-ui',
  /// );
  /// ```
  void mountAxleDocs({
    required String spec,
    String specPath = '/openapi.json',
    String docsPath = '/docs',
    String? title,
    String swaggerUiUrl = defaultSwaggerUiUrl,
    String? swaggerUiDirectory,
    String swaggerUiPath = '/docs-assets',
    bool noCache = true,
  }) {
    final localAssetsPath = swaggerUiDirectory == null
        ? null
        : _normalizePrefix(swaggerUiPath);
    final docs = AxleDocs(
      spec: spec,
      specPath: specPath,
      docsPath: docsPath,
      title: title,
      swaggerUiUrl: localAssetsPath ?? swaggerUiUrl,
      noCache: noCache,
    );
    if (localAssetsPath != null &&
        (localAssetsPath == '/' ||
            localAssetsPath == docs.specPath ||
            localAssetsPath == docs.docsPath)) {
      throw ArgumentError.value(
        swaggerUiPath,
        'swaggerUiPath',
        'must not be `/`, the spec path, or the docs path.',
      );
    }

    get(docs.specPath, (Request request) => _jsonResponse(docs));
    get(
      docs.docsPath,
      (Request request) => Response.ok(
        body: Body.fromString(docs.uiHtml, mimeType: MimeType.html),
        headers: _headers(docs.headers),
      ),
    );
    if (swaggerUiDirectory != null) {
      mountSwaggerUiAssets(
        swaggerUiDirectory,
        pathPrefix: localAssetsPath!,
        noCache: noCache,
      );
    }
  }

  /// Mounts Swagger UI assets generated by `axle gen`.
  ///
  /// [directory] is the `generate.output.ui` directory. Files are registered
  /// under [pathPrefix]; use the same prefix as `swaggerUiPath` on
  /// [mountAxleDocs].
  void mountSwaggerUiAssets(
    String directory, {
    String pathPrefix = '/docs-assets',
    bool noCache = true,
  }) {
    final root = Directory(directory).absolute;
    if (!root.existsSync()) {
      throw ArgumentError.value(
        directory,
        'directory',
        'does not exist. Run `dart run axle_cli:axle gen` first.',
      );
    }

    final rootPath = root.resolveSymbolicLinksSync();
    final assets = root
        .listSync(recursive: true, followLinks: false)
        .whereType<File>()
        .where((file) => p.isWithin(rootPath, file.resolveSymbolicLinksSync()))
        .toList();
    if (assets.isEmpty) {
      throw ArgumentError.value(
        directory,
        'directory',
        'contains no Swagger UI assets. Run `dart run axle_cli:axle gen` '
            'first.',
      );
    }

    final prefix = _normalizePrefix(pathPrefix);
    for (final file in assets) {
      final relative = p.relative(file.path, from: root.path);
      final route = '$prefix/${p.url.joinAll(p.split(relative))}';
      final bytes = file.readAsBytesSync();
      final contentType =
          lookupMimeType(file.path) ?? 'application/octet-stream';
      get(
        route,
        (Request request) =>
            _assetResponse(bytes, contentType, noCache: noCache),
      );
    }
  }
}

Response _jsonResponse(AxleDocs docs) {
  return Response.ok(
    body: Body.fromString(docs.specJson, mimeType: MimeType.json),
    headers: _headers(docs.headers),
  );
}

Response _assetResponse(
  Uint8List bytes,
  String contentType, {
  required bool noCache,
}) {
  return Response.ok(
    body: Body.fromData(bytes, mimeType: MimeType.parse(contentType)),
    headers: noCache ? _cacheHeaders() : null,
  );
}

Headers? _headers(Map<String, String> values) {
  if (values.isEmpty) return null;
  return Headers.fromMap({
    for (final entry in values.entries) entry.key: [entry.value],
  });
}

Headers _cacheHeaders() => Headers.fromMap(const {
  'cache-control': ['no-store'],
});

String _normalizePrefix(String path) {
  final trimmed = path.trim();
  if (trimmed.isEmpty) {
    throw ArgumentError.value(path, 'pathPrefix', 'must not be empty');
  }
  final withLeading = trimmed.startsWith('/') ? trimmed : '/$trimmed';
  if (withLeading.length > 1 && withLeading.endsWith('/')) {
    return withLeading.substring(0, withLeading.length - 1);
  }
  return withLeading;
}
