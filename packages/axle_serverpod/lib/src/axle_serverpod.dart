/// Serverpod integration for axle.
library;

import 'dart:async';
import 'dart:io';

import 'package:axle_core/axle_core.dart';
import 'package:serverpod/serverpod.dart';

/// A Serverpod route that serves the Swagger UI page for [docs].
///
/// Mount it at [AxleDocs.docsPath] with [WebServer.addRoute], or use
/// [AxleServerpodDocs.mountAxleDocs] to register the complete documentation
/// surface.
class AxleDocsRoute extends Route {
  /// Creates a route serving the Swagger UI described by [docs].
  AxleDocsRoute(this.docs) : super(methods: {Method.get}, path: '/');

  /// The documentation payload served by this route.
  final AxleDocs docs;

  /// Returns the Swagger UI page.
  @override
  FutureOr<Result> handleCall(Session session, Request request) =>
      swaggerUiResponse(docs);
}

/// A Serverpod route that serves the OpenAPI JSON document for [docs].
///
/// Mount it at [AxleDocs.specPath] with [WebServer.addRoute], or use
/// [AxleServerpodDocs.mountAxleDocs] to register the complete documentation
/// surface.
class AxleOpenApiRoute extends Route {
  /// Creates a route serving the OpenAPI document described by [docs].
  AxleOpenApiRoute(this.docs) : super(methods: {Method.get}, path: '/');

  /// The documentation payload served by this route.
  final AxleDocs docs;

  /// Returns the OpenAPI document as JSON.
  @override
  FutureOr<Result> handleCall(Session session, Request request) =>
      openApiJsonResponse(docs);
}

/// Adds axle documentation routes to a Serverpod [WebServer].
extension AxleServerpodDocs on WebServer {
  /// Mounts the generated OpenAPI document and Swagger UI.
  ///
  /// [spec] is the JSON string produced by `axle gen`. The document is served
  /// at [specPath] and the UI at [docsPath]. Both paths must start with `/`.
  ///
  /// When [title] is omitted, the UI title is read from the document's
  /// `info.title`.
  ///
  /// Pass [swaggerUiDirectory] to serve the assets generated by `axle gen` from
  /// that directory. The UI then loads assets from [swaggerUiPath]. When
  /// [swaggerUiDirectory] is omitted, the UI uses [swaggerUiUrl], which
  /// defaults to the pinned CDN distribution.
  ///
  /// Each path is absolute on the web server, so the docs can be mounted
  /// anywhere:
  ///
  /// ```dart
  /// pod.webServer.mountAxleDocs(
  ///   spec: axleOpenApiJson,
  ///   specPath: '/internal/api/openapi.json',
  ///   docsPath: '/internal/api/reference',
  ///   swaggerUiDirectory: 'assets/swagger-ui',
  ///   swaggerUiPath: '/internal/api/assets',
  /// );
  /// ```
  ///
  /// These routes run on the Serverpod **web server** port, not the API server
  /// port. Register them before `pod.start()`.
  ///
  /// ```dart
  /// import 'package:axle_serverpod/axle_serverpod.dart';
  /// import 'package:your_package/src/generated/openapi.g.dart';
  ///
  /// pod.webServer.mountAxleDocs(
  ///   spec: axleOpenApiJson,
  ///   swaggerUiDirectory: 'assets/swagger-ui',
  /// );
  /// ```
  AxleDocs mountAxleDocs({
    required String spec,
    String specPath = '/openapi.json',
    String docsPath = '/docs',
    String? title,
    String swaggerUiUrl = defaultSwaggerUiUrl,
    String? swaggerUiDirectory,
    String swaggerUiPath = '/docs-assets',
    bool noCache = true,
  }) {
    final localAssetsPath = swaggerUiDirectory == null
        ? null
        : _normalizePrefix(swaggerUiPath);
    final docs = AxleDocs(
      spec: spec,
      specPath: specPath,
      docsPath: docsPath,
      title: title,
      swaggerUiUrl: localAssetsPath ?? swaggerUiUrl,
      noCache: noCache,
    );
    if (localAssetsPath != null &&
        (localAssetsPath == '/' ||
            localAssetsPath == docs.specPath ||
            localAssetsPath == docs.docsPath)) {
      throw ArgumentError.value(
        swaggerUiPath,
        'swaggerUiPath',
        'must not be `/`, the spec path, or the docs path.',
      );
    }
    if (swaggerUiDirectory != null) {
      _requireAssetsDirectory(swaggerUiDirectory);
    }

    addRoute(AxleOpenApiRoute(docs), docs.specPath);
    addRoute(AxleDocsRoute(docs), docs.docsPath);
    if (swaggerUiDirectory != null) {
      mountSwaggerUiAssets(
        swaggerUiDirectory,
        pathPrefix: localAssetsPath!,
        noCache: noCache,
      );
    }
    return docs;
  }

  /// Mounts Swagger UI assets generated by `axle gen`.
  ///
  /// [directory] is the `generate.output.ui` directory. Files are served below
  /// [pathPrefix]; use the same prefix as `swaggerUiPath` on [mountAxleDocs].
  ///
  /// Throws an [ArgumentError] when [directory] does not exist or contains no
  /// files.
  void mountSwaggerUiAssets(
    String directory, {
    String pathPrefix = '/docs-assets',
    bool noCache = true,
  }) {
    final prefix = _normalizePrefix(pathPrefix);
    _requireAssetsDirectory(directory);
    addRoute(
      StaticRoute.directory(
        Directory(directory),
        cacheControlFactory: noCache ? StaticRoute.noStore() : null,
      ),
      prefix,
    );
  }
}

/// Builds the OpenAPI JSON response for [docs].
Response openApiJsonResponse(AxleDocs docs) {
  return Response.ok(
    body: Body.fromString(docs.specJson, mimeType: MimeType.json),
    headers: _headers(docs.headers),
  );
}

/// Builds the Swagger UI response for [docs].
Response swaggerUiResponse(AxleDocs docs) {
  return Response.ok(
    body: Body.fromString(docs.uiHtml, mimeType: MimeType.html),
    headers: _headers(docs.headers),
  );
}

Headers? _headers(Map<String, String> values) {
  if (values.isEmpty) return null;
  return Headers.fromMap({
    for (final entry in values.entries) entry.key: [entry.value],
  });
}

void _requireAssetsDirectory(String directory) {
  final root = Directory(directory);
  if (!root.existsSync()) {
    throw ArgumentError.value(
      directory,
      'directory',
      'does not exist. Run `dart run axle_cli:axle gen` first.',
    );
  }
  final hasFiles = root
      .listSync(recursive: true, followLinks: false)
      .any((entry) => entry is File);
  if (!hasFiles) {
    throw ArgumentError.value(
      directory,
      'directory',
      'contains no Swagger UI assets. Run `dart run axle_cli:axle gen` '
          'first.',
    );
  }
}

String _normalizePrefix(String path) {
  final trimmed = path.trim();
  if (trimmed.isEmpty) {
    throw ArgumentError.value(path, 'pathPrefix', 'must not be empty');
  }
  final withLeading = trimmed.startsWith('/') ? trimmed : '/$trimmed';
  if (withLeading.length > 1 && withLeading.endsWith('/')) {
    return withLeading.substring(0, withLeading.length - 1);
  }
  return withLeading;
}
